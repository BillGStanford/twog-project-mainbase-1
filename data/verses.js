export function searchVerses(q) {
  const lower = q.toLowerCase();
  return verses.filter(v =>
    v.text.toLowerCase().includes(lower) ||
    v.reference.toLowerCase().includes(lower) ||
    v.context.toLowerCase().includes(lower) ||
    v.subcategory.toLowerCase().includes(lower) ||
    v.book.toLowerCase().includes(lower)
  );
}